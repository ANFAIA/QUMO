# --------------------------------------------------------------------------- discovery
@dataclass
class Example:
    path: str  # repo-relative, POSIX separators
    kind: str  # mojo | qasm | py
    title: str = ""
    sources: list[str] = field(default_factory=list)
    reproduces: str = ""
    meta: dict | None = None
    meta_error: str = ""
    legacy: bool = False
    helper: bool = False

    @property
    def framework(self) -> str:
        if self.meta and self.meta.get("framework"):
            return str(self.meta["framework"])
        return "qumo"

    @property
    def tier(self) -> str:
        return str(self.meta.get("tier", "fast")) if self.meta else "fast"

    @property
    def timeout(self) -> float:
        if self.meta and "timeout" in self.meta:
            return float(self.meta["timeout"])
        return float(LEGACY_TIMEOUT)

    @property
    def requires(self) -> list[str]:
        return [str(r) for r in (self.meta or {}).get("requires", [])]

    def args(self, gpu: bool = False) -> list[str]:
        meta = self.meta or {}
        if gpu and "gpu_args" in meta:
            return [str(a) for a in meta["gpu_args"]]
        return [str(a) for a in meta.get("args", [])]


def _strip_comment(line: str) -> str:
    s = line.strip()
    for prefix in ("///", "//", "#", "*"):
        if s.startswith(prefix):
            return s[len(prefix):].strip()
    return s


def _title_from(text: str, kind: str) -> str:
    lines = text.splitlines()
    if kind in ("mojo", "py"):
        for ln in lines[:40]:
            s = ln.strip()
            if s.startswith(("#!", "# -*-")) or not s:
                continue
            if s.startswith(('"""', "'''", 'r"""')):
                body = s.lstrip("r")[3:].strip()
                if body.endswith(('"""', "'''")):
                    body = body[:-3].strip()
                if body:
                    return body.rstrip(".")
                continue
            if s.startswith("#"):
                continue
            return s.rstrip(".")
    for ln in lines[:20]:
        s = ln.strip()
        if s.startswith("//"):
            body = _strip_comment(s)
            if body and not body.lower().startswith(("example-meta", "source:", "reproduces:")):
                return body.rstrip(".")
    return ""


def parse_header(text: str, kind: str) -> dict:
    """Title, Source URLs, Reproduces text and example-meta of one example file."""
    out: dict = {"title": _title_from(text, kind), "sources": [], "reproduces": "", "meta": None,
                 "meta_error": "", "meta_lines": 0, "has_main": False}
    for ln in text.splitlines()[:200]:
        m = _RE_META.search(ln)
        if m:
            out["meta_lines"] += 1
            try:
                meta = json.loads(m.group(1))
                if not isinstance(meta, dict):
                    raise ValueError("not a JSON object")
                out["meta"] = meta
            except ValueError as exc:
                out["meta_error"] = f"invalid example-meta JSON ({exc})"
            continue
        m = _RE_SOURCE.match(ln)
        if m and m.group(1).startswith(("http://", "https://")):
            out["sources"].append(m.group(1).rstrip(").,;"))
            continue
        m = _RE_REPRO.match(ln)
        if m and not out["reproduces"]:
            out["reproduces"] = m.group(1)
    if out["meta_lines"] > 1:
        out["meta_error"] = f"{out['meta_lines']} example-meta lines (exactly one expected)"
    out["has_main"] = "__main__" in text or "def main()" in text
    return out


def validate_meta(meta: dict) -> list[str]:
    """Problems with one example-meta object ([] = valid)."""
    errs = []
    missing = META_KEYS - set(meta)
    if missing:
        errs.append(f"example-meta lacks {sorted(missing)}")
    unknown = set(meta) - META_KEYS - OPTIONAL_META_KEYS
    if unknown:
        errs.append(f"example-meta has unknown keys {sorted(unknown)}")
    if "tier" in meta and meta["tier"] not in TIERS:
        errs.append(f"tier must be one of {TIERS}, got {meta['tier']!r}")
    if "timeout" in meta and not (isinstance(meta["timeout"], (int, float)) and 0 < meta["timeout"] <= 3600):
        errs.append(f"timeout must be a number in (0, 3600], got {meta['timeout']!r}")
    for key in ("requires", "args", "gpu_args"):
        if key in meta and not (isinstance(meta[key], list) and all(isinstance(a, str) for a in meta[key])):
            errs.append(f"{key} must be a list of strings")
    if "framework" in meta and not (isinstance(meta["framework"], str) and meta["framework"]):
        errs.append("framework must be a non-empty string")
    return errs


def _excluded(rel: Path, include_hardware: bool, include_references: bool) -> bool:
    parts = rel.parts
    if any(p in EXCLUDED_DIRS for p in parts[:-1]):
        return True
    if parts[0] == "hardware" and not include_hardware:
        return True
    if "reference" in parts[:-1] and not include_references:
        return True
    name = parts[-1]
    if name.startswith("_") or name.startswith("test_") or name == "run_examples.py":
        return True
    return False


def discover(root: Path = EXAMPLES, include_hardware: bool = False, include_references: bool = False,
             repo: Path = REPO) -> list[Example]:
    out: list[Example] = []
    for f in sorted(root.rglob("*")):
        if not f.is_file() or f.suffix not in (".mojo", ".qasm", ".py"):
            continue
        rel = f.relative_to(root)
        if _excluded(rel, include_hardware, include_references):
            continue
        kind = f.suffix[1:]
        text = f.read_text(encoding="utf-8", errors="replace")
        h = parse_header(text, kind)
        try:
            path = f.relative_to(repo).as_posix()
        except ValueError:
            path = f.as_posix()
        ex = Example(path, kind, h["title"], h["sources"], h["reproduces"], h["meta"], h["meta_error"])
        if ex.meta is None and not ex.meta_error:
            in_subdir = len(rel.parts) > 1
            if kind == "py" and in_subdir and "__main__" not in text:
                ex.helper = True  # imported by an example, not run on its own
            else:
                ex.legacy = True
        out.append(ex)
    return out


# --------------------------------------------------------------------------- requirements
def _paths(gpu: bool, repo: Path = REPO) -> dict[str, Path]:
    build = repo / "build" / "gpu" if gpu else repo / "build"
    return {"build": build, "cli": build / "qumo", "qumo_py": build / "qumo_py.so"}


def _have_module(python: str, mod: str) -> bool:
    if Path(python).resolve() == Path(sys.executable).resolve():
        try:
            return importlib.util.find_spec(mod) is not None
        except (ImportError, ValueError):
            return False
    try:
        r = subprocess.run([python, "-c", f"import importlib.util,sys; sys.exit(0 if importlib.util.find_spec({mod!r}) else 1)"],
                           capture_output=True, timeout=60)
        return r.returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


_GPU_USABLE: dict[str, tuple[bool, str]] = {}


def gpu_usable(repo: Path = REPO, python: str | None = None) -> tuple[bool, str]:
    """(usable, reason) from build/gpu/qumo_py.so's gpu_info(), cached."""
    key = str(repo)
    if key in _GPU_USABLE:
        return _GPU_USABLE[key]
    so = repo / "build" / "gpu" / "qumo_py.so"
    if not so.is_file():
        res = (False, "build/gpu/qumo_py.so missing (make py-gpu)")
    else:
        code = ("import sys,json; sys.path.insert(0, sys.argv[1]); import qumo_py as q; "
                "g = q.gpu_info(); print(json.dumps({'a': bool(g['compiled'] and g['available']), 'e': str(g['error'])}))")
        try:
            r = subprocess.run([python or default_python(), "-c", code, str(so.parent)], capture_output=True,
                               text=True, timeout=120)
            d = json.loads(r.stdout.strip().splitlines()[-1])
            res = (True, "") if d["a"] else (False, f"no usable GPU ({d['e'] or 'gpu_info().available is false'})")
        except Exception as exc:  # noqa: BLE001 - any failure means "not usable"
            res = (False, f"gpu_info() failed ({type(exc).__name__})")
    _GPU_USABLE[key] = res
    return res


def default_python() -> str:
    return str(BENCH_PY) if BENCH_PY.is_file() else sys.executable


def unmet_requirement(ex: Example, gpu: bool, python: str, repo: Path = REPO) -> str:
    """'' when every requirement is met, else the SKIP reason."""
    p = _paths(gpu, repo)
    reqs = list(ex.requires)
    if ex.kind == "qasm" and "cli" not in reqs:
        reqs.append("cli")
    if ex.kind == "mojo" and not MOJO.is_file() and repo == REPO:
        return "Mojo toolchain missing (.venv/bin/mojo; make setup)"
    if ex.meta and ex.meta.get("skip_reason"):
        return str(ex.meta["skip_reason"])
    for r in reqs:
        if r == "cli":
            if not p["cli"].is_file():
                return f"requires cli: {p['cli'].relative_to(repo)} missing (make {'cli-gpu' if gpu else 'cli'})"
        elif r == "qumo_py":
            if not p["qumo_py"].is_file():
                return f"requires qumo_py: {p['qumo_py'].relative_to(repo)} missing (make {'py-gpu' if gpu else 'py'})"
        elif r == "gpu":
            if not gpu:
                return "requires gpu: run with --gpu after building qumo_py with GPU support"
            ok, why = gpu_usable(repo, python)
            if not ok:
                return f"requires gpu: {why}"
        elif r == "network":
            if os.environ.get("QUMO_EXAMPLES_NETWORK") != "1":
                return "requires network: set QUMO_EXAMPLES_NETWORK=1 to allow network access"
        elif r == "torch":
            if not _have_module(python, "torch"):
                return "requires torch: not importable in the example Python"
        elif r.startswith("phase2:") or r == "phase2":
            return f"requires {r}: not available yet"
        else:
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_.]*", r):
                return f"unknown requirement {r!r}"
            if not _have_module(python, r):
                return f"requires {r}: not importable in the example Python"
    return ""


# --------------------------------------------------------------------------- running
@dataclass
class Result:
    path: str
    kind: str
    framework: str
    tier: str
    status: str  # PASS | FAIL | SKIP | TIMEOUT
    seconds: float = 0.0
    reason: str = ""
    checks: list[dict] = field(default_factory=list)
    checks_passed: int = 0
    checks_failed: int = 0
    legacy: bool = False
    command: list[str] = field(default_factory=list)
    returncode: int | None = None
    tail: str = ""


def build_command(ex: Example, gpu: bool, python: str, repo: Path = REPO) -> tuple[list[str], dict]:
    p = _paths(gpu, repo)
    env = dict(os.environ)
    env.setdefault("PYTHONUNBUFFERED", "1")
    if ex.kind == "mojo":
        cmd = [str(MOJO), "run", "-I", "."] + (["-D", "QUMO_GPU"] if gpu else []) + [ex.path] + ex.args(gpu)
    elif ex.kind == "qasm":
        override = LEGACY_OVERRIDES.get(ex.path) if ex.legacy else None
        if override:
            cmd = [str(p["cli"])] + [a.replace("{file}", ex.path) for a in override]
        else:
            cmd = [str(p["cli"]), "run", ex.path, "--shots", "1000", "--seed", "1", "--json"] + ex.args(gpu)
    else:
        cmd = [python, ex.path] + ex.args(gpu)
        extra = [str(p["build"]), str(repo / "plugins" / "hardware")]
        env["PYTHONPATH"] = os.pathsep.join(extra + ([env["PYTHONPATH"]] if env.get("PYTHONPATH") else []))
        if p["qumo_py"].is_file():
            env["QUMO_PY_PATH"] = str(p["qumo_py"])
        env["QUMO_CLI"] = str(p["cli"])
        env["QUMO_EXAMPLES_GPU"] = "1" if gpu else "0"
    return cmd, env


def parse_checks(output: str) -> tuple[list[dict], int | None]:
    checks = []
    all_passed = None
    for ln in output.splitlines():
        s = ln.rstrip()
        m = _RE_CHECK.match(s)
        if m:
            checks.append({"label": m.group("label"), "status": m.group("status"), "detail": m.group("detail") or ""})
            continue
        m = _RE_ALL.match(s)
        if m:
            all_passed = int(m.group(1))
    return checks, all_passed


def judge(ex: Example, returncode: int | None, output: str, timed_out: bool) -> tuple[str, str, list[dict]]:
    checks, all_passed = parse_checks(output)
    failed = [c for c in checks if c["status"] == "FAIL"]
    if timed_out:
        return "TIMEOUT", f"exceeded {ex.timeout:g} s", checks
    if returncode != 0:
        why = f"exit status {returncode}"
        if failed:
            why += f"; failed checks: {', '.join(c['label'] for c in failed)}"
        return "FAIL", why, checks
    if ex.legacy:
        return "PASS", "smoke test (no example-meta)", checks
    if failed:
        return "FAIL", f"failed checks: {', '.join(c['label'] for c in failed)}", checks
    if all_passed is None:
        return "FAIL", "no 'ALL CHECKS PASSED' line", checks
    if all_passed != len(checks):
        return "FAIL", f"ALL CHECKS PASSED ({all_passed}) but {len(checks)} CHECK lines were printed", checks
    return "PASS", "", checks


def run_one(ex: Example, gpu: bool = False, python: str | None = None, repo: Path = REPO,
            timeout_scale: float = 1.0) -> Result:
    python = python or default_python()
    res = Result(ex.path, ex.kind, ex.framework, ex.tier, "SKIP", legacy=ex.legacy)
    if ex.meta_error:
        res.status, res.reason = "FAIL", ex.meta_error
        return res
    if ex.meta is not None:
        errs = validate_meta(ex.meta)
        if errs:
            res.status, res.reason = "FAIL", "; ".join(errs)
            return res
    why = unmet_requirement(ex, gpu, python, repo)
    if why:
        res.reason = why
        return res
    cmd, env = build_command(ex, gpu, python, repo)
    res.command = cmd
    timeout = ex.timeout * timeout_scale
    t0 = time.perf_counter()
    timed_out = False
    try:
        proc = subprocess.run(cmd, cwd=repo, env=env, capture_output=True, text=True, timeout=timeout,
                              errors="replace")
        output, rc = proc.stdout + ("\n" + proc.stderr if proc.stderr else ""), proc.returncode
    except subprocess.TimeoutExpired as exc:
        timed_out = True
        out = exc.stdout or b""
        output = out.decode(errors="replace") if isinstance(out, bytes) else out
        rc = None
    except OSError as exc:
        output, rc = f"{type(exc).__name__}: {exc}", 127
    res.seconds = round(time.perf_counter() - t0, 3)
    res.returncode = rc
    res.status, res.reason, res.checks = judge(ex, rc, output, timed_out)
    res.checks_passed = sum(1 for c in res.checks if c["status"] == "PASS")
    res.checks_failed = sum(1 for c in res.checks if c["status"] == "FAIL")
    if res.status != "PASS":
        lines = [ln for ln in output.splitlines() if "Crashpad" not in ln]
        res.tail = "\n".join(lines[-25:])
    return res


def select(examples: list[Example], tier: str, only: list[str] | None) -> list[Example]:
    out = [e for e in examples if not e.helper]
    if only:
        wanted = []
        for o in only:
            o_norm = Path(o).as_posix().lstrip("./")
            wanted.append(o_norm)
        out = [e for e in out if any(e.path == w or e.path.startswith(w.rstrip("/") + "/") or w in e.path
                                     for w in wanted)]
        return out
    if tier != "all":
        out = [e for e in out if e.tier == tier]
    return out


def run_all(examples: list[Example], jobs: int = 2, gpu: bool = False, python: str | None = None,
            repo: Path = REPO, progress=None) -> list[Result]:
    results: dict[str, Result] = {}
    with cf.ThreadPoolExecutor(max_workers=max(1, jobs)) as pool:
        futs = {pool.submit(run_one, ex, gpu, python, repo): ex for ex in examples}
        for fut in cf.as_completed(futs):
            r = fut.result()
            results[r.path] = r
            if progress:
                progress(r)
    return [results[e.path] for e in examples]


def format_table(results: list[Result]) -> str:
    w = max([len(r.path) for r in results] + [7])
    lines = [f"{'example':<{w}}  {'status':<7}  {'seconds':>8}  checks  note", "-" * (w + 40)]
    for r in results:
        checks = f"{r.checks_passed}/{r.checks_passed + r.checks_failed}" if (r.checks or not r.legacy) else "-"
        lines.append(f"{r.path:<{w}}  {r.status:<7}  {r.seconds:8.2f}  {checks:>6}  {r.reason}")
    counts = {s: sum(1 for r in results if r.status == s) for s in ("PASS", "FAIL", "TIMEOUT", "SKIP")}
    total = sum(r.seconds for r in results)
    lines.append("-" * (w + 40))
    lines.append(f"{counts['PASS']} passed, {counts['FAIL']} failed, {counts['TIMEOUT']} timed out, "
                 f"{counts['SKIP']} skipped; {total:.1f} s of example time")
    return "\n".join(lines)


def write_report(results: list[Result], path: Path, args: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    doc = {
        "schema": "qumo.examples_report.v1",
        "generated_unix": int(time.time()),
        "args": args,
        "summary": {s: sum(1 for r in results if r.status == s) for s in ("PASS", "FAIL", "TIMEOUT", "SKIP")},
        "total_seconds": round(sum(r.seconds for r in results), 3),
        "results": [asdict(r) for r in results],
    }
    path.write_text(json.dumps(doc, indent=1) + "\n", encoding="utf-8")


# --------------------------------------------------------------------------- index
def _md_link(ex: Example, base: Path) -> str:
    rel = os.path.relpath(REPO / ex.path, base) if not Path(ex.path).is_absolute() else ex.path
    return f"[`{Path(ex.path).name}`]({Path(rel).as_posix()})"


def _cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ").strip()


def _sources_md(ex: Example) -> str:
    if not ex.sources:
        return ""
    parts = []
    for i, url in enumerate(ex.sources):
        label = "source" if i == 0 else f"source {i + 1}"
        parts.append(f"[{label}]({url})")
    return ", ".join(parts)


def frameworks_index(examples: list[Example]) -> str:
    """examples/frameworks/README.md (fully generated)."""
    base = EXAMPLES / "frameworks"
    fw = [e for e in examples if e.path.startswith("examples/frameworks/") and not e.helper and e.meta]
    by: dict[str, list[Example]] = {}
    for e in fw:
        by.setdefault(Path(e.path).parts[2] if len(Path(e.path).parts) > 3 else e.framework, []).append(e)
    lines = [
        "# Framework examples reproduced with QUMO",
        "",
        "<!-- Generated by `bench/.venv/bin/python examples/run_examples.py --write-index`; do not edit by hand. -->",
        "",
        "Each file re-implements a published tutorial or demo from another quantum framework on QUMO's own",
        "API, cites the original (`Source:`), and verifies its numbers with machine-readable `CHECK` lines",
        "(page values, analytic values or a pinned reference run). No framework is a dependency: the",
        "originals' SDKs are only used, optionally, by the scripts in `reference/` folders.",
        "",
        "Run one: `.venv/bin/mojo run -I . examples/frameworks/<framework>/<file>.mojo`.",
        "Run all: `bench/.venv/bin/python examples/run_examples.py --only examples/frameworks`.",
        "",
    ]
    if not by:
        lines += ["_No framework examples yet._", ""]
    for key in sorted(by):
        lines += [f"## {FRAMEWORK_NAMES.get(key, key)}", "", "| Example | Reproduces | Tier | Original |",
                  "|---|---|---|---|"]
        for e in sorted(by[key], key=lambda x: x.path):
            lines.append(f"| {_md_link(e, base)} — {_cell(e.title)} | {_cell(e.reproduces)} | {e.tier} | "
                         f"{_sources_md(e)} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def readme_table(examples: list[Example]) -> str:
    """The generated block inside examples/README.md."""
    base = EXAMPLES
    groups: dict[str, list[Example]] = {}
    for e in examples:
        if e.helper:
            continue
        parts = Path(e.path).parts
        folder = parts[1] if len(parts) > 2 else "."
        groups.setdefault(folder, []).append(e)
    lines = [INDEX_BEGIN, "",
             "Every example below is run and verified by `bench/.venv/bin/python examples/run_examples.py`",
             "(`--tier fast` by default; `--tier all` adds the slow tier). Status lines are `CHECK <label>: PASS|FAIL ...`.", "",
             "| Folder | Examples | Frameworks | Fast / slow |", "|---|---|---|---|"]
    for folder in sorted(groups):
        es = groups[folder]
        fws = sorted({e.framework for e in es if not e.legacy}) or ["qumo (legacy smoke tests)"]
        fast = sum(1 for e in es if e.tier == "fast")
        slow = sum(1 for e in es if e.tier == "slow")
        link = "[`examples/`](.)" if folder == "." else f"[`{folder}/`]({folder}/)"
        lines.append(f"| {link} | {len(es)} | {', '.join(fws)} | {fast} / {slow} |")
    lines.append("")
    new = [e for e in examples if not e.helper and not e.legacy and not e.path.startswith("examples/frameworks/")]
    if new:
        lines += ["| Example | Framework | Tier | Reproduces |", "|---|---|---|---|"]
        for e in sorted(new, key=lambda x: x.path):
            rel = Path(e.path).relative_to("examples").as_posix()
            lines.append(f"| [`{rel}`]({rel}) — {_cell(e.title)} | {e.framework} | {e.tier} | "
                         f"{_cell(e.reproduces)} |")
        lines.append("")
    lines += ["Framework reproductions (Qiskit, Braket, Q#, TKET, CUDA-Q, Cirq, Qibo) are indexed in",
              "[`frameworks/README.md`](frameworks/README.md).", "", INDEX_END]
    return "\n".join(lines)


def splice_readme(text: str, block: str) -> str:
    if INDEX_BEGIN in text and INDEX_END in text:
        head = text[: text.index(INDEX_BEGIN)]
        tail = text[text.index(INDEX_END) + len(INDEX_END):]
        return head + block + tail
    sep = "" if text.endswith("\n\n") else ("\n" if text.endswith("\n") else "\n\n")
    return text + sep + "## Index\n\n" + block + "\n"


def header_problems(examples: list[Example]) -> list[str]:
    errs = []
    for e in examples:
        if e.helper:
            continue
        if e.meta_error:
            errs.append(f"{e.path}: {e.meta_error}")
            continue
        if e.legacy:
            # legacy top-level examples predate the header convention; new folders must comply
            if len(Path(e.path).parts) > 2:
                errs.append(f"{e.path}: no example-meta line")
            continue
        for msg in validate_meta(e.meta or {}):
            errs.append(f"{e.path}: {msg}")
        if not e.sources:
            errs.append(f"{e.path}: no 'Source: <url>' line")
        if not e.reproduces:
            errs.append(f"{e.path}: no 'Reproduces:' line")
        if not e.title:
            errs.append(f"{e.path}: no title (first docstring/comment line)")
    return errs


def index_outputs(examples: list[Example]) -> dict[Path, str]:
    readme = EXAMPLES / "README.md"
    current = readme.read_text(encoding="utf-8") if readme.is_file() else "# QUMO examples\n"
    return {
        EXAMPLES / "frameworks" / "README.md": frameworks_index(examples),
        readme: splice_readme(current, readme_table(examples)),
    }


def check_urls(examples: list[Example], timeout: float = 15.0) -> list[str]:
    """HEAD every Source URL (network; run by a human, never in CI)."""
    import urllib.error
    import urllib.request

    bad = []
    seen: set[str] = set()
    for e in examples:
        for url in e.sources:
            if url in seen:
                continue
            seen.add(url)
            req = urllib.request.Request(url, method="HEAD", headers={"User-Agent": "qumo-examples-link-check"})
            try:
                with urllib.request.urlopen(req, timeout=timeout) as r:  # noqa: S310 - fixed https URLs from headers
                    if r.status >= 400:
                        bad.append(f"{e.path}: {url} -> HTTP {r.status}")
            except urllib.error.HTTPError as exc:
                if exc.code == 405:  # HEAD not allowed: retry with GET
                    try:
                        with urllib.request.urlopen(url, timeout=timeout) as r:  # noqa: S310
                            if r.status < 400:
                                continue
                    except Exception as exc2:  # noqa: BLE001
                        bad.append(f"{e.path}: {url} -> {type(exc2).__name__}")
                        continue
                bad.append(f"{e.path}: {url} -> HTTP {exc.code}")
            except Exception as exc:  # noqa: BLE001
                bad.append(f"{e.path}: {url} -> {type(exc).__name__}")
    return bad


# --------------------------------------------------------------------------- CLI
def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tier", choices=["fast", "slow", "all"], default="fast")
    ap.add_argument("--only", nargs="+", metavar="PATH", help="run only these files or folders")
    ap.add_argument("--gpu", action="store_true", help="-D QUMO_GPU for Mojo, build/gpu/ for the CLI and qumo_py")
    ap.add_argument("-j", "--jobs", type=int, default=2)
    ap.add_argument("--list", action="store_true", help="list the selected examples and exit")
    ap.add_argument("--json", default=str(REPO / "build" / "examples_report.json"), metavar="OUT")
    ap.add_argument("--write-index", action="store_true")
    ap.add_argument("--check-index", action="store_true")
    ap.add_argument("--include-hardware", action="store_true")
    ap.add_argument("--include-references", action="store_true")
    ap.add_argument("--check-urls", action="store_true", help="HEAD every Source URL (needs network)")
    ap.add_argument("--python", default=None, help="interpreter for Python examples (default bench/.venv)")
    a = ap.parse_args(argv)

    examples = discover(include_hardware=a.include_hardware, include_references=a.include_references)

    if a.write_index or a.check_index:
        rc = 0
        outputs = index_outputs(examples)
        if a.write_index:
            for p, text in outputs.items():
                p.parent.mkdir(parents=True, exist_ok=True)
                old = p.read_text(encoding="utf-8") if p.is_file() else None
                if old != text:
                    p.write_text(text, encoding="utf-8")
                    print(f"wrote {p.relative_to(REPO)}")
                else:
                    print(f"unchanged {p.relative_to(REPO)}")
        if a.check_index:
            errs = header_problems(examples)
            for p, text in outputs.items():
                old = p.read_text(encoding="utf-8") if p.is_file() else None
                if old != text:
                    errs.append(f"{p.relative_to(REPO)} is stale: run examples/run_examples.py --write-index")
            for e in errs:
                print("INDEX ERROR", e)
            print("index OK" if not errs else f"{len(errs)} index problem(s)")
            rc = 1 if errs else 0
        if not a.check_urls:
            return rc

    if a.check_urls:
        bad = check_urls([e for e in examples if not e.helper])
        for b in bad:
            print("URL", b)
        print("urls OK" if not bad else f"{len(bad)} bad URL(s)")
        return 1 if bad else 0

    chosen = select(examples, a.tier, a.only)
    if a.list:
        for e in chosen:
            flag = "legacy" if e.legacy else e.tier
            print(f"{e.path}  [{e.kind}, {e.framework}, {flag}, timeout {e.timeout:g} s]"
                  + (f"  requires={e.requires}" if e.requires else ""))
        print(f"{len(chosen)} example(s)")
        return 0
    if not chosen:
        print("no examples selected")
        return 1

    def progress(r: Result) -> None:
        print(f"{r.status:<7} {r.seconds:7.2f}s  {r.path}" + (f"  ({r.reason})" if r.reason else ""), flush=True)
        if r.status in ("FAIL", "TIMEOUT") and r.tail:
            print("        " + r.tail.replace("\n", "\n        "), flush=True)

    t0 = time.perf_counter()
    results = run_all(chosen, a.jobs, a.gpu, a.python, REPO, progress)
    wall = time.perf_counter() - t0
    print()
    print(format_table(results))
    print(f"wall time {wall:.1f} s with -j {a.jobs}")
    out = Path(a.json)
    write_report(results, out, {"tier": a.tier, "only": a.only, "gpu": a.gpu, "jobs": a.jobs,
                                "wall_seconds": round(wall, 3)})
    print(f"report: {out}")
    return 1 if any(r.status in ("FAIL", "TIMEOUT") for r in results) else 0


if __name__ == "__main__":
    sys.exit(main())
