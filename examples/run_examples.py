#!/usr/bin/env python3
"""Run, verify and index QUMO's examples.

Every example under examples/ declares a header (module docstring for Mojo and
Python, `//` comments for OpenQASM):

    <title>
    Reproduces: <Framework> - <original title>
    Source: <exact URL of the original>          (one or more)
    example-meta: {"framework": "qiskit", "tier": "fast", "timeout": 60, "requires": [], "args": []}

and prints machine-readable `CHECK <label>: PASS|FAIL ...` lines through
qumo.testing.checks.CheckLog (Mojo) or examples/_checks.py (Python), ending with
`ALL CHECKS PASSED (n)`.

Usage (from the repository root):

    bench/.venv/bin/python examples/run_examples.py                 # fast tier, -j 2
    bench/.venv/bin/python examples/run_examples.py --tier all
    bench/.venv/bin/python examples/run_examples.py --only examples/frameworks/qiskit/chsh.mojo
    bench/.venv/bin/python examples/run_examples.py --gpu           # -D QUMO_GPU, build/gpu/*
    bench/.venv/bin/python examples/run_examples.py --list
    bench/.venv/bin/python examples/run_examples.py --write-index   # regenerate the README indexes
    bench/.venv/bin/python examples/run_examples.py --check-index   # CI: headers valid, indexes current

Discovery: *.mojo, *.qasm and *.py under examples/, excluding examples/colab/,
examples/hardware/ (unless --include-hardware), `reference/` folders (unless
--include-references), files starting with '_' and test_*.py. A Python file in
a sub-folder without `example-meta:` and without a `__main__` guard is a helper
module and is not run. Files without metadata (the legacy examples) run as
smoke tests: exit 0 within 120 s.

Pass rule: exit status 0, `ALL CHECKS PASSED` printed, no `CHECK ...: FAIL`
line, finished within the timeout. A smoke test only needs exit 0 in time. An
unmet requirement (gpu, qumo_py, cli, torch, network, or any importable
Python module name) is a SKIP with the reason, never a FAIL.

Output: a table, plus build/examples_report.json (status, seconds, every
CHECK line). Exit status 1 if anything FAILed or timed out.
"""

