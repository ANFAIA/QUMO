"""High-level workflow shared by the CLI, the examples and agents.

    plan()   compile with QUMO -> translate -> provider validation -> cost estimate
    run()    plan() + safety gate + submit (+ wait) ; dry-run safe by default
    job_status() / job_result()   work from any process via the local job store

Safety model: anything that leaves this machine (`requires_confirmation`) is
only submitted when the caller passes `confirm=True` (CLI: `--yes`). Without
it, `run()` raises QM-E957 carrying the full plan (backend, shots, cost), so a
human or an agent can review it first. `dry_run=True` never submits. Providers
enforce the same rule again in `submit(..., confirm=...)`.

Waiting: `run(wait=True)` polls until the job reaches a final state or
`timeout`. A job that ends in ERROR/CANCELLED is reported with
`status` = that state and a `warning` (the CLI exits with code 1). If the
caller interrupts the wait (Ctrl-C), the KeyboardInterrupt propagates with the
submitted job id attached as `exc.qumo_job_id`; `on_submitted(job)` is called
right after submission so a caller can record or print the id first.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from typing import Any

from . import jobs as job_store
from .base import BIT_ORDER, DONE, FINAL_STATES, CostEstimate, JobHandle, requires_confirmation
from .compile import CompiledCircuit, compile_for_target
from .errors import E_CONFIRM, E_JOB, E_LIMIT, HINT_COST, HINT_SHOTS, HardwareError

MOCK_WARNING = ("IBM server-side dry run: these counts are mock data generated by the service, "
                "not measurements from a QPU")
from .registry import get_provider


@dataclass
class Plan:
    provider: Any
    backend: str
    shots: int
    compiled: CompiledCircuit
    payload: Any
    report: dict
    validation: dict
    cost: CostEstimate
    comparison: dict | None = None
    submit_payload: Any = None
    notes: list[str] = field(default_factory=list)

    @property
    def requires_confirmation(self) -> bool:
        return requires_confirmation(self.provider, self.backend)

    def to_dict(self, include_qasm: bool = False) -> dict:
        d = {
            "provider": self.provider.name,
            "backend": self.backend,
            "shots": self.shots,
            "local": self.provider.is_local(self.backend),
            "requires_confirmation": self.requires_confirmation,
            "cost": self.cost.to_dict(),
            "cost_summary": self.cost.summary(),
            "compiled": self.compiled.summary(),
            "target": self.compiled.target.to_dict(compact=True),
            "validation": self.validation,
            "finishing": self.report,
            "bit_order": BIT_ORDER,
        }
        if self.comparison is not None:
            d["comparison"] = self.comparison
        if self.notes:
            d["notes"] = self.notes
        if include_qasm:
            d["qasm"] = self.compiled.qasm
        return d


def plan(source: Any, provider: Any, backend: str, shots: int = 1000, level: int = 2, seed: int = 1,
         provider_transpile: bool = False, params: Any = None) -> Plan:
    """Compile `source` with QUMO for `backend` and estimate the cost. Never submits."""
    if isinstance(provider, str):
        provider = get_provider(provider)
    spec = provider.target(backend)
    if shots < 1 or shots > spec.max_shots:
        raise HardwareError(E_LIMIT, f"shots must be in 1..{spec.max_shots} for {backend}", HINT_SHOTS)
    compiled = compile_for_target(source, spec, level=level, seed=seed, params=params)
    payload, report = provider.prepare(compiled, backend)
    validation = provider.validate(payload, backend)
    p = Plan(provider, backend, shots, compiled, payload, report or {}, validation,
             provider.estimate_cost(compiled, shots, backend, payload=payload))
    p.submit_payload = payload
    p.notes.extend(str(n) for n in (spec.extras or {}).get("warnings", []))
    if provider_transpile:
        if not hasattr(provider, "provider_compile"):
            p.notes.append(f"provider '{provider.name}' has no native compiler hook; using QUMO's payload")
        else:
            theirs = provider.provider_compile(compiled, backend)
            provider.validate(theirs, backend)
            p.comparison = {"qumo": provider.circuit_stats(payload, backend),
                            "provider": provider.circuit_stats(theirs, backend)}
            p.submit_payload = theirs
            p.report = {"passes": ["provider preset pass manager (comparison mode)"]}
            p.cost = provider.estimate_cost(compiled, shots, backend, payload=theirs)
    return p


def run(source: Any, provider: Any, backend: str, shots: int = 1000, level: int = 2, seed: int = 1,
        dry_run: bool = False, confirm: bool = False, max_cost: float | None = None, wait: bool = True,
        timeout: float = 600.0, poll: float = 5.0, provider_transpile: bool = False,
        include_qasm: bool = False, params: Any = None, on_submitted: Any = None) -> dict:
    """Plan, gate and (maybe) submit. Returns a JSON-ready dict.

    Output keys besides the plan: `dry_run`, `submitted`, `job_id`, `status`,
    `counts`; `server_dry_run` / `mock_results` + `warning` when the provider
    returned mock data (IBM `--ibm-dry-run`); `warning` + `next` when the job
    has no result (still queued at `timeout`, or ended in ERROR/CANCELLED)."""
    if isinstance(provider, str):
        provider = get_provider(provider)
    p = plan(source, provider, backend, shots, level, seed, provider_transpile, params)
    out = p.to_dict(include_qasm=include_qasm)
    if dry_run:
        out.update({"dry_run": True, "submitted": False})
        return out
    if max_cost is not None and p.cost.billable and p.cost.amount > max_cost:
        raise HardwareError(E_LIMIT, f"estimated cost {p.cost.summary()} exceeds --max-cost {max_cost}",
                            HINT_COST, details={"plan": out})
    if p.requires_confirmation and not confirm:
        raise HardwareError(
            E_CONFIRM,
            f"not submitted: '{backend}' is a remote {provider.name} backend; {shots} shots, "
            f"estimated cost {p.cost.summary()}",
            details={"plan": out},
        )
    job = provider.submit(p.compiled, shots, backend, seed=seed, payload=p.submit_payload, report=p.report,
                          max_cost=max_cost, confirm=True)  # the gate above is the confirmation
    job.meta["provider_options"] = getattr(provider, "public_options", dict)()
    job.meta["cost"] = p.cost.to_dict()
    job_store.save(job)
    out.update({"dry_run": False, "submitted": True, "job_id": job.job_id, "status": job.status})
    out.update(_mock_flags(job))
    if on_submitted is not None:
        on_submitted(job)
    if job.local:
        out["counts"] = job.counts
        return out
    if wait:
        try:
            res = job_result(job.job_id, wait=True, timeout=timeout, poll=poll, provider=provider)
            out.update({"status": res["status"], "counts": res.get("counts")})
        except HardwareError as exc:  # still queued after `timeout`, or failed: the job *was* submitted
            if exc.code != E_JOB:
                raise
            out.update({"status": job_store.load(job.job_id).status, "warning": str(exc),
                        "next": f"python -m qumo_hardware result {job.job_id} --wait"})
        except KeyboardInterrupt as exc:
            exc.qumo_job_id = job.job_id  # the job keeps running at the provider
            raise
    return out


def _mock_flags(job: JobHandle) -> dict:
    if job.meta.get("mock_results") or job.meta.get("server_dry_run"):
        return {"server_dry_run": True, "mock_results": True, "warning": MOCK_WARNING}
    return {}


def _provider_for(job: JobHandle, provider: Any = None):
    if provider is not None:
        return provider
    return get_provider(job.provider, **(job.meta.get("provider_options") or {}))


def job_status(job_id: str, provider: Any = None) -> dict:
    job = job_store.load(job_id)
    prov = _provider_for(job, provider)
    st = prov.status(job)
    if st != job.status:
        job.status = st
        job_store.save(job)
    return {"job_id": job.job_id, "provider": job.provider, "backend": job.backend, "shots": job.shots,
            "status": st, "local": job.local, "submitted_at": job.submitted_at}


def job_result(job_id: str, wait: bool = False, timeout: float = 600.0, poll: float = 5.0,
               provider: Any = None) -> dict:
    job = job_store.load(job_id)
    prov = _provider_for(job, provider)
    if job.counts is None:
        deadline = time.monotonic() + timeout
        st = prov.status(job)
        while wait and st not in FINAL_STATES and time.monotonic() < deadline:
            time.sleep(poll)
            st = prov.status(job)
        job.status = st
        if st != DONE:
            job_store.save(job)
            raise HardwareError(E_JOB, f"job '{job_id}' is {st}; no result yet" if st not in FINAL_STATES
                                else f"job '{job_id}' ended with status {st}")
        job.counts = prov.result(job)
        job_store.save(job)
    counts = dict(job.counts)
    out = {"job_id": job.job_id, "provider": job.provider, "backend": job.backend, "status": DONE,
           "shots": job.shots, "counts": counts, "num_clbits": job.meta.get("num_clbits"),
           "most_frequent": max(counts, key=counts.get) if counts else None, "bit_order": BIT_ORDER}
    out.update(_mock_flags(job))
    return out


def list_backends(provider: str, online: bool = False, **options: Any) -> list[dict]:
    prov = get_provider(provider, **options)
    return [b.to_dict() for b in prov.list_backends(online=online)]
