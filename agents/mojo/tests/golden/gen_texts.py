"""Writes agents/mojo/qumo_agent/harness/texts.mojo from deepagents_golden.json (DESIGN.md 2.7.12).

Dev-time only, standard library only:

    python3 -I agents/mojo/tests/golden/gen_texts.py

The constants are never retyped by hand: regenerate the golden with gen_golden.py, then
run this script.
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
OUT = REPO / "agents" / "mojo" / "qumo_agent" / "harness" / "texts.mojo"

HEADER = '''"""Portions ported from deepagents 0.7.32 and langchain 1.4.8 / langchain-core 1.7.4
(Copyright (c) LangChain, Inc., MIT License; see agents/mojo/LICENSES/langchain-MIT.txt).

Verbatim deepagents / langchain / langgraph texts (DESIGN.md Appendix A) and the texts
written for this port's merged file tools (Appendix B.1).

GENERATED by agents/mojo/tests/golden/gen_texts.py from
agents/mojo/tests/golden/deepagents_golden.json. Do not edit by hand.

`{name}` fields are Python `str.format` placeholders; the harness fills them with
`String.replace`. `*_PARAMETERS` constants are compact JSON texts (key order kept).
"""
'''


def mojo_literal(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif o < 0x20 or o == 0x7F:
            out.append("\\x%02x" % o)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def compact(v):
    return json.dumps(v, ensure_ascii=False, separators=(",", ":"))


def main():
    g = json.loads((HERE / "deepagents_golden.json").read_text(encoding="utf-8"))
    lines = [HEADER]
    names = []
    lines.append("# --- texts " + "-" * 70)
    for name, value in g["texts"].items():
        lines.append(f"comptime {name} = {mojo_literal(value)}")
        names.append(name)
    lines.append("")
    lines.append("# --- tool parameter schemas (wire JSON) " + "-" * 40)
    for name, value in g["schemas"].items():
        lines.append(f"comptime {name} = {mojo_literal(compact(value))}")
        names.append(name)
    lines.append("")
    lines.append("# --- token-count schemas (tool_call_schema minus top-level title/description) ---")
    count_names = []
    for tool, value in g["count_parameters"].items():
        cname = "COUNT_PARAMETERS_" + tool.upper()
        lines.append(f"comptime {cname} = {mojo_literal(compact(value))}")
        count_names.append((tool, cname))
    lines.append("")
    lines.append("# --- A.11 non-text extensions: (lower-cased suffix, content type, mime) ---")
    lines.append("comptime MEDIA_EXTENSIONS: List[String] = [" + ", ".join(mojo_literal(k) for k in g["media"]) + "]")
    lines.append("comptime MEDIA_TYPES: List[String] = [" + ", ".join(mojo_literal(v[0]) for v in g["media"].values()) + "]")
    lines.append("comptime MEDIA_MIMES: List[String] = [" + ", ".join(mojo_literal(v[1]) for v in g["media"].values()) + "]")
    lines.append("")
    lines.append("")
    lines.append("def count_parameters(tool: String) -> String:")
    lines.append('    """COUNT_PARAMETERS[tool] for the deepagents tools; "" for any other name."""')
    for tool, cname in count_names:
        lines.append(f"    if tool == {mojo_literal(tool)}:")
        lines.append(f"        return {cname}")
    lines.append("    return String()")
    lines.append("")
    lines.append("")
    lines.append("def text_table() -> List[Tuple[String, String]]:")
    lines.append('    """(name, value) of every text and schema constant, for test_harness_texts."""')
    lines.append("    var t = List[Tuple[String, String]]()")
    for name in names:
        lines.append(f'    t.append(("{name}", String({name})))')
    for tool, cname in count_names:
        lines.append(f'    t.append(("{cname}", String({cname})))')
    lines.append("    return t^")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
